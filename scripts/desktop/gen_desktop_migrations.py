#!/usr/bin/env python3
"""
Generates the desktop Room migrations from upstream's Android migrations.

The desktop database started at schema 214, so it needs every migration from 214 upward. Each one
in app/.../migrations/Migrations.kt must consist only of db.execSQL(...) calls; their SQL
expressions are copied verbatim into connection.execSQL(...) calls. Anything else stops the
generator, so a migration with logic is ported by hand instead of silently skipped.

usage: python3 -I scripts/desktop/gen_desktop_migrations.py
"""
import re
import sys
from pathlib import Path

FIRST = 214
SRC = Path("app/src/main/kotlin/com/nendo/argosy/data/local/migrations/Migrations.kt")
OUT = Path("shared/src/desktopMain/kotlin/com/nendo/argosy/data/local/DesktopMigrations.kt")

text = SRC.read_text(encoding="utf-8")
found = {}
for m in re.finditer(r"^object Migration_(\d+)_(\d+) : Migration\(\d+, \d+\) \{\n", text, re.M):
    start, end = int(m.group(1)), int(m.group(2))
    if start < FIRST:
        continue
    i, depth = m.end(), 1
    while depth:
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        i += 1
    body = text[m.end():i - 1]
    inner = re.search(r"override fun migrate\(db: SupportSQLiteDatabase\) \{\n(.*)\n    \}\s*$", body, re.S)
    if not inner:
        sys.exit(f"Migration_{start}_{end}: unexpected shape; port it by hand")
    stmts, j, code = [], 0, inner.group(1)
    while True:
        k = code.find("db.execSQL(", j)
        if k < 0:
            if code[j:].strip():
                sys.exit(f"Migration_{start}_{end}: code besides db.execSQL; port it by hand")
            break
        if code[j:k].strip():
            sys.exit(f"Migration_{start}_{end}: code besides db.execSQL; port it by hand")
        p, depth, inside = k + len("db.execSQL("), 1, None
        while depth:
            c = code[p]
            if inside:
                if c == "\\":
                    p += 1
                elif c == inside:
                    inside = None
            elif c == '"':
                inside = '"'
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            p += 1
        stmts.append(code[k + len("db.execSQL("):p - 1].strip())
        j = p
    found[(start, end)] = stmts

steps = sorted(found)
for a, b in zip(steps, steps[1:]):
    if a[1] != b[0]:
        sys.exit(f"gap between {a} and {b}")

lines = [
    "package com.nendo.argosy.data.local",
    "",
    "import androidx.room.migration.Migration",
    "import androidx.sqlite.SQLiteConnection",
    "import androidx.sqlite.execSQL",
    "",
    "/**",
    " * Upstream's Room migrations from schema 214, the version the desktop database started at, for the",
    " * bundled SQLite driver. Generated by scripts/desktop/gen_desktop_migrations.py from",
    " * app/.../migrations/Migrations.kt; regenerate after an upstream merge instead of editing.",
    " */",
    "object DesktopMigrations {",
]
names = []
for start, end in steps:
    name = f"MIGRATION_{start}_{end}"
    names.append(name)
    lines.append(f"    val {name} = object : Migration({start}, {end}) {{")
    lines.append("        override fun migrate(connection: SQLiteConnection) {")
    for s in found[(start, end)]:
        expr = "\n".join(("            " + l.strip()) if n else l for n, l in enumerate(s.split("\n")))
        lines.append(f"            connection.execSQL({expr})")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
lines.append("    val ALL: Array<Migration> = arrayOf(" + ", ".join(names) + ")")
lines.append("}")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT}: {len(names)} migrations, {steps[0][0]} -> {steps[-1][1]}")
